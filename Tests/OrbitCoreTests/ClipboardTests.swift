    @Suite struct PasteboardFilterTests {
        /// Password managers mark their copies; those must never be stored.
        @Test func skipsConcealedAndTransient() {
            let plain = "public.utf8-plain-text"
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                           "de.petermaurer.TransientPasteboardType"] {
                #expect(!PasteboardFilter.shouldRecord(types: [plain, marker]), "\(marker) must be skipped")
                #expect(!PasteboardFilter.shouldRecord(types: [marker, plain]), "order must not matter for \(marker)")
                #expect(!PasteboardFilter.shouldRecord(types: [marker]))
            }
            // 1Password's marker has version-suffixed variants.
            #expect(!PasteboardFilter.shouldRecord(types: [plain, "com.agilebits.onepassword.item"]))
        }

        @Test func recordsOrdinaryTypes() {
            #expect(PasteboardFilter.shouldRecord(types: ["public.utf8-plain-text"]))
            #expect(PasteboardFilter.shouldRecord(types: ["public.utf8-plain-text", "public.rtf", "public.html"]))
            #expect(PasteboardFilter.shouldRecord(types: ["public.png", "public.tiff"]))
