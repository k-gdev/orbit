            #expect(String(decoding: capture.payload, as: UTF8.self) == "Hello, world")
        }

        @Test func previewCollapsesWhitespaceAndTruncates() {
            #expect(ClipboardItem.makePreview("  a\n\n  b\t c  ") == "a b c")
            let long = String(repeating: "x", count: 500)
            #expect(ClipboardItem.makePreview(long).count == 200)
            #expect(ClipboardItem.makePreview("") == "")
            #expect(ClipboardItem.makePreview("   \n ") == "")
            // Emoji and combining marks count as single characters, not bytes.
            #expect(ClipboardItem.makePreview(String(repeating: "👨‍👩‍👧", count: 300)).count == 200)
        }

        @Test func hashSeparatesKindsAndContent() {
            let a = ClipboardHash.make(kind: .text, payload: Data("abc".utf8))
            #expect(a == ClipboardHash.make(kind: .text, payload: Data("abc".utf8)))
            #expect(a != ClipboardHash.make(kind: .text, payload: Data("abd".utf8)))
            #expect(a != ClipboardHash.make(kind: .richText, payload: Data("abc".utf8)))
            #expect(a.count == 64)
        }

        @Test func capturesForOtherKinds() {
            let rtf = ClipboardCapture.richText(rtf: Data("{\\rtf1 hi}".utf8), plain: "hi there", sourceBundleID: nil, sourceName: nil, date: .now)
            #expect(rtf.kind == .richText)
