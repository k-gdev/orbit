import Foundation
import Testing
@testable import OrbitCore

/// Clipboard history (spec §5.5): what is recorded, how the history behaves, its limits, its persistence
/// and its settings. Everything here is pure or runs in a temp folder / throwaway defaults suite.
@Suite struct ClipboardTests {
    // MARK: Pasteboard filter

    @Suite struct PasteboardFilterTests {
        /// Password managers mark their copies; those must never be stored.
        @Test func skipsConcealedAndTransient() {
            let plain = "public.utf8-plain-text"
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                           "de.petermaurer.TransientPasteboardType"] {
                #expect(!PasteboardFilter.shouldRecord(types: [plain, marker]), "\(marker) must be skipped")
                #expect(!PasteboardFilter.shouldRecord(types: [marker, plain]), "order must not matter for \(marker)")
                #expect(!PasteboardFilter.shouldRecord(types: [marker]))
            }
            // 1Password's marker has version-suffixed variants.
            #expect(!PasteboardFilter.shouldRecord(types: [plain, "com.agilebits.onepassword.item"]))
        }

        @Test func recordsOrdinaryTypes() {
            #expect(PasteboardFilter.shouldRecord(types: ["public.utf8-plain-text"]))
            #expect(PasteboardFilter.shouldRecord(types: ["public.utf8-plain-text", "public.rtf", "public.html"]))
            #expect(PasteboardFilter.shouldRecord(types: ["public.png", "public.tiff"]))
            #expect(PasteboardFilter.shouldRecord(types: ["public.file-url"]))
            // The nspasteboard "source" marker only names the app; it is not a reason to skip.
            #expect(PasteboardFilter.shouldRecord(types: ["public.utf8-plain-text", "org.nspasteboard.source"]))
            #expect(PasteboardFilter.shouldRecord(types: []))
        }

        @Test func ignoredAppsAreSkipped() {
            let types = ["public.utf8-plain-text"]
            #expect(!PasteboardFilter.shouldRecord(types: types, sourceBundleID: "com.apple.keychainaccess",
                                                   ignoredBundleIDs: ["com.apple.keychainaccess"]))
            #expect(PasteboardFilter.shouldRecord(types: types, sourceBundleID: "com.apple.Safari",
                                                  ignoredBundleIDs: ["com.apple.keychainaccess"]))
            #expect(PasteboardFilter.shouldRecord(types: types, sourceBundleID: nil, ignoredBundleIDs: ["com.apple.keychainaccess"]))
            // Markers win over an app that is not ignored.
            #expect(!PasteboardFilter.shouldRecord(types: types + ["org.nspasteboard.ConcealedType"],
                                                   sourceBundleID: "com.apple.Safari", ignoredBundleIDs: []))
        }
    }

    // MARK: History

    static let base = Date(timeIntervalSince1970: 2_000_000)

    /// A text entry made `minutesAgo` before `base`.
    static func item(_ text: String, minutesAgo: Double = 0, source: String? = nil, pinned: Bool = false,
                     size: Int? = nil) -> ClipboardItem {
        var item = ClipboardCapture.text(text, sourceBundleID: source.map { "com.example.\($0)" }, sourceName: source,
                                         date: base.addingTimeInterval(-minutesAgo * 60)).makeItem(payloadFile: "\(text).txt")
        item.pinned = pinned
        if let size { item.byteSize = size }
        return item
    }

    @Suite struct ClipboardHistoryTests {
        @Test func addPutsNewestFirst() {
            var history = ClipboardHistory()
            let a = ClipboardTests.item("a")
            let b = ClipboardTests.item("b")
            let first = history.add(a)
            #expect(first == .inserted)
            let second = history.add(b)
            #expect(second == .inserted)
            #expect(history.items.map(\.preview) == ["b", "a"])
            #expect(history.totalBytes == 2)
            #expect(history.count == 2)
        }

        @Test func duplicateMovesToTop() {
            var history = ClipboardHistory()
            var a = ClipboardTests.item("a", minutesAgo: 10, source: "Safari")
            a.pinned = true
            history.add(a)
            history.add(ClipboardTests.item("b", minutesAgo: 5))
            history.add(ClipboardTests.item("c", minutesAgo: 1))
            #expect(history.items.map(\.preview) == ["c", "b", "a"])

            // Copy "a" again, from another app, with a fresh blob that nothing will reference.
            var again = ClipboardTests.item("a", minutesAgo: 0, source: "Notes")
            again.payloadFile = "other-blob.txt"
            let result = history.add(again)
            #expect(result == .movedToTop(unusedPayload: "other-blob.txt"))
            #expect(history.items.map(\.preview) == ["a", "c", "b"])
            #expect(history.count == 3)
            let top = history.items[0]
            #expect(top.id == a.id, "the original entry is kept")
            #expect(top.pinned, "its pin survives")
            #expect(top.date == again.date, "the date is the latest copy's")
            #expect(top.sourceName == "Notes", "the source is the latest copy's")
            #expect(top.payloadFile == "a.txt")

            // A duplicate that brings no new blob has nothing to throw away.
            var bare = ClipboardTests.item("b")
            bare.payloadFile = nil
            let bareResult = history.add(bare)
            #expect(bareResult == .movedToTop(unusedPayload: nil))
            #expect(history.items.map(\.preview) == ["b", "a", "c"])
        }

        @Test func togglePinAndRemove() {
            var history = ClipboardHistory()
            let a = ClipboardTests.item("a")
            history.add(a)
            let pinned = history.togglePin(id: a.id)
            #expect(pinned == true)
            #expect(history.items[0].pinned)
            let unpinned = history.togglePin(id: a.id)
            #expect(unpinned == false)
            let missingPin = history.togglePin(id: UUID())
            #expect(missingPin == nil)
            let missingRemove = history.remove(id: UUID())
            #expect(missingRemove == nil)
            let removed = history.remove(id: a.id)
            #expect(removed?.id == a.id)
            #expect(history.isEmpty)
        }

        @Test func pinSurvivesClear() {
            var history = ClipboardHistory()
            history.add(ClipboardTests.item("old", minutesAgo: 30, pinned: true))
            history.add(ClipboardTests.item("x", minutesAgo: 20))
            history.add(ClipboardTests.item("y", minutesAgo: 10))
            let removed = history.clear(keepPinned: true)
            #expect(removed.map(\.preview) == ["y", "x"])
            #expect(history.items.map(\.preview) == ["old"])
            // Clearing everything, pins included, is still available.
            let rest = history.clear(keepPinned: false)
            #expect(rest.map(\.preview) == ["old"])
            #expect(history.isEmpty)
        }

        @Test func displayOrderPutsPinnedFirst() {
            var history = ClipboardHistory()
            history.add(ClipboardTests.item("p1", minutesAgo: 50, pinned: true))
            history.add(ClipboardTests.item("a", minutesAgo: 40))
            history.add(ClipboardTests.item("p2", minutesAgo: 30, pinned: true))
            history.add(ClipboardTests.item("b", minutesAgo: 20))
            #expect(history.displayItems.map(\.preview) == ["p2", "p1", "b", "a"])
            #expect(history.search("").map(\.preview) == ["p2", "p1", "b", "a"])
            #expect(history.search("   ").map(\.preview) == ["p2", "p1", "b", "a"])
        }

        @Test func searchIsCaseAndDiacriticInsensitive() {
            var history = ClipboardHistory()
            history.add(ClipboardTests.item("Café menu: crème brûlée", minutesAgo: 3, source: "Notes"))
            history.add(ClipboardTests.item("ÉCOLE report", minutesAgo: 2, source: "Pages"))
            history.add(ClipboardTests.item("plain text", minutesAgo: 1, source: "Safari"))
            #expect(history.search("cafe").map(\.preview) == ["Café menu: crème brûlée"])
            #expect(history.search("CAFÉ").map(\.preview) == ["Café menu: crème brûlée"])
            #expect(history.search("creme brulee").map(\.preview) == ["Café menu: crème brûlée"])
            #expect(history.search("ecole").map(\.preview) == ["ÉCOLE report"])
            #expect(history.search("école").map(\.preview) == ["ÉCOLE report"])
            // The source app's name is searched too.
            #expect(history.search("safari").map(\.preview) == ["plain text"])
            #expect(history.search("NOTES").map(\.preview) == ["Café menu: crème brûlée"])
            // Every word has to match, in any order.
            #expect(history.search("report ecole").map(\.preview) == ["ÉCOLE report"])
            #expect(history.search("report safari").isEmpty)
            #expect(history.search("zzz").isEmpty)
        }

        @Test func moveToTopOnUse() {
            var history = ClipboardHistory()
            let a = ClipboardTests.item("a", minutesAgo: 2)
            history.add(a)
            history.add(ClipboardTests.item("b", minutesAgo: 1))
            let moved = history.moveToTop(id: a.id, date: ClipboardTests.base)
            #expect(moved)
            #expect(history.items.map(\.preview) == ["a", "b"])
            #expect(history.items[0].date == ClipboardTests.base)
            let movedMissing = history.moveToTop(id: UUID(), date: ClipboardTests.base)
            #expect(!movedMissing)
        }

        @Test func lookupsByIDAndHash() {
            var history = ClipboardHistory()
            let a = ClipboardTests.item("a")
            history.add(a)
            #expect(history.item(id: a.id) == a)
            #expect(history.item(id: UUID()) == nil)
            #expect(history.contains(contentHash: a.contentHash))
            #expect(!history.contains(contentHash: "nope"))
        }
    }

    // MARK: Items and captures

    @Suite struct ClipboardItemTests {
        @Test func recordsPlainText() throws {
            let capture = ClipboardCapture.text("Hello, world", sourceBundleID: "com.apple.Safari", sourceName: "Safari",
                                                date: Date(timeIntervalSince1970: 1_000))
            let item = capture.makeItem(payloadFile: "abc.txt")
            #expect(item.kind == .text)
            #expect(item.preview == "Hello, world")
            #expect(item.sourceBundleID == "com.apple.Safari")
            #expect(item.sourceName == "Safari")
            #expect(item.date == Date(timeIntervalSince1970: 1_000))
            #expect(item.byteSize == 12)
            #expect(item.payloadFile == "abc.txt")
            #expect(!item.pinned)
            #expect(item.contentHash.count == 64)
            #expect(String(decoding: capture.payload, as: UTF8.self) == "Hello, world")
        }

        @Test func previewCollapsesWhitespaceAndTruncates() {
            #expect(ClipboardItem.makePreview("  a\n\n  b\t c  ") == "a b c")
            let long = String(repeating: "x", count: 500)
            #expect(ClipboardItem.makePreview(long).count == 200)
            #expect(ClipboardItem.makePreview("") == "")
            #expect(ClipboardItem.makePreview("   \n ") == "")
            // Emoji and combining marks count as single characters, not bytes.
            #expect(ClipboardItem.makePreview(String(repeating: "👨‍👩‍👧", count: 300)).count == 200)
        }

        @Test func hashSeparatesKindsAndContent() {
            let a = ClipboardHash.make(kind: .text, payload: Data("abc".utf8))
            #expect(a == ClipboardHash.make(kind: .text, payload: Data("abc".utf8)))
            #expect(a != ClipboardHash.make(kind: .text, payload: Data("abd".utf8)))
            #expect(a != ClipboardHash.make(kind: .richText, payload: Data("abc".utf8)))
            #expect(a.count == 64)
        }

        @Test func capturesForOtherKinds() {
            let rtf = ClipboardCapture.richText(rtf: Data("{\\rtf1 hi}".utf8), plain: "hi there", sourceBundleID: nil, sourceName: nil, date: .now)
            #expect(rtf.kind == .richText)
            #expect(rtf.preview == "hi there")
            #expect(rtf.makeItem(payloadFile: nil).byteSize == 10)

            let image = ClipboardCapture.image(png: Data(repeating: 1, count: 2_048), width: 1920, height: 1080,
                                               sourceBundleID: nil, sourceName: nil, date: .now)
            #expect(image.kind == .image)
            #expect(image.preview == "Image 1920 × 1080")
            #expect(image.makeItem(payloadFile: nil).byteSize == 2_048)

            let files = ClipboardCapture.files(paths: ["/Users/k/Desktop/report.pdf", "/Users/k/Desktop/notes.txt"],
                                               sourceBundleID: "com.apple.finder", sourceName: "Finder", date: .now)
            #expect(files.kind == .files)
            #expect(files.preview == "report.pdf, notes.txt")
            #expect(ClipboardPayload.filePaths(from: files.payload) == ["/Users/k/Desktop/report.pdf", "/Users/k/Desktop/notes.txt"])
            #expect(ClipboardPayload.filePaths(from: Data("not json".utf8)) == [])
        }

        @Test func ageLabels() {
            let now = Date(timeIntervalSince1970: 1_000_000)
            func label(_ secondsAgo: TimeInterval) -> String {
                ClipboardItem.ageLabel(for: now.addingTimeInterval(-secondsAgo), now: now)
            }
            #expect(label(0) == "just now")
            #expect(label(59) == "just now")
            #expect(label(60) == "1 min ago")
            #expect(label(59 * 60) == "59 min ago")
            #expect(label(3_600) == "1 h ago")
            #expect(label(23 * 3_600) == "23 h ago")
            #expect(label(24 * 3_600) == "Yesterday")
            #expect(label(3 * 86_400) == "3 d ago")
            // A date slightly in the future (clock change) is "just now", not negative.
            #expect(label(-30) == "just now")
        }

        @Test func itemRoundTripsThroughJSON() throws {
            let item = ClipboardCapture.text("é", sourceBundleID: nil, sourceName: nil, date: Date(timeIntervalSince1970: 5)).makeItem(payloadFile: "x.txt")
            let data = try JSONEncoder().encode(item)
            #expect(try JSONDecoder().decode(ClipboardItem.self, from: data) == item)
        }
    }
